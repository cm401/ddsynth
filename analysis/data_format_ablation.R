# =============================================================================
# data_format_ablation.R
# -----------------------------------------------------------------------------
# "Data-format ablation" experiment on the real dataset.
#
# For every pathogen that has at least MIN_DATASETS_PER_ARM datasets of
# individual-level format (summary types 4/5: exact or interval-censored
# frequency tables) AND at least MIN_DATASETS_PER_ARM datasets of summary-
# statistic format (types 1/2/3: median+range, median+IQR, mean+SD), the
# script fits three model versions:
#
#   A. Individual-level only   — summary types 4 and 5 only
#   B. Summary-statistics only — summary types 1, 2, and 3 only
#   C. Federated / full model  — all available data formats jointly
#
# Comparison metrics (per pathogen × distribution):
#
#   Posterior summaries (all three arms)
#     pred_median   posterior predictive median (days): median (2.5%, 97.5%)
#     pred_q95      posterior predictive 95th percentile (days)
#     tau           between-study SD: median (2.5%, 97.5%); "— (n<5)" when sparse
#
#   Uncertainty
#     width            95% CrI width of pred_median (posterior uncertainty)
#     interval_ratio   A_width / C_width and B_width / C_width; > 1 = federated is
#                      tighter
#     norm_shift       (C_median − arm_median) / arm_width; normalised shift in units
#                      of arm's own uncertainty (|shift| > 0.5 = meaningful pull)
#
#   Distributional discrepancy (posterior-median predictive CDFs)
#     W2       Wasserstein-2 distance (days); quantile-function L2 over [0.1%, 99.9%]
#     JS       Jensen-Shannon divergence (bits, base-2); symmetric, bounded [0, 1]
#     OVL      Overlap coefficient ∫ min(f_A, f_C) dx; 1 = identical, 0 = disjoint
#
#   Tail probabilities  P(T > d | arm) at TAIL_THRESHOLDS (days)
#     ptail_d_A, ptail_d_B, ptail_d_C   (one triplet per threshold)
#
#   LOO/ELPD
#     elpd / elpd_se   study-level PSIS-LOO ELPD (NA when n_datasets < 4)
#     n_k_high         number of studies with Pareto k̂ > 0.7 (LOO reliability flag)
#
#   Differences  (federated minus single-arm, posterior-median point estimates)
#     delta_CA_median, delta_CA_q95
#     delta_CB_median, delta_CB_q95
#
# LOO/ELPD notes
# --------------
# log_lik[n_datasets * 3] is generated by the Stan model.  For types 1/2, the
# three entries per study are the individual order-statistic contributions; for
# types 3/4/5 only the first entry is used (unused slots are 0).  Summing each
# triplet gives a per-study log-likelihood matrix for study-level PSIS-LOO.
# ELPD values are comparable within an arm across distributions but NOT across
# arms — each arm conditions on a different number and type of observations.
#
# Distributional-metric notes
# ---------------------------
# W2, JS, and OVL are computed from the posterior-median predictive CDF, i.e.
# the CDF at the draw-wise median of the predictive distribution.  This is a
# single representative distribution, not a posterior average; it is consistent
# with how pred_median and pred_q95 are reported.  All three metrics compare
# two arms pairwise: (A, C), (B, C), and (A, B).
#
# Output
# ------
#   results/data_format_ablation.rds  — nested list of stanfit objects + tables
#   results/data_format_ablation.csv  — main comparison table (wide format)
#
# Results file format:
#   $ablation_fits[[pathogen]][[arm]][[dist]]
#     $fit        rstan stanfit object (NULL if sampling failed)
#     $stan_data  list passed to Stan
#     $datasets   dataset list used for this arm
#     $skipped    TRUE + $reason when deliberately skipped
#   $comparison_tbl  data.frame with all comparison columns
# =============================================================================

