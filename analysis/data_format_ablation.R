# Study-level PSIS-LOO ELPD using the log_lik triplets from Stan.
# Returns list(elpd, se, n_k_high) — all NA/0 on failure or when n < 4.
.compute_loo_elpd <- function(fit, n_datasets) {
  na_res <- list(elpd = NA_real_, se = NA_real_, n_k_high = NA_integer_)
  if (is.null(fit) || n_datasets < 4L) return(na_res)

  ll_raw <- tryCatch(
    rstan::extract(fit, pars = "log_lik")$log_lik,
    error = function(e) NULL
  )
  if (is.null(ll_raw) || ncol(ll_raw) != n_datasets * 3L) return(na_res)

  n_draws <- nrow(ll_raw)
  ll_per_study <- matrix(0, nrow = n_draws, ncol = n_datasets)
  for (d in seq_len(n_datasets)) {
    base <- (d - 1L) * 3L + 1L
    ll_per_study[, d] <- ll_raw[, base] + ll_raw[, base + 1L] + ll_raw[, base + 2L]
  }
  ll_per_study[!is.finite(ll_per_study)] <- -700

  loo_res <- tryCatch(
    loo::loo(ll_per_study, r_eff = rep(1, n_datasets)),
    error = function(e) NULL
  )
  if (is.null(loo_res)) return(na_res)

  n_k_high <- sum(loo_res$diagnostics$pareto_k > 0.7, na.rm = TRUE)

  list(
    elpd     = loo_res$estimates["elpd_loo", "Estimate"],
    se       = loo_res$estimates["elpd_loo", "SE"],
    n_k_high = n_k_high
  )
}

# Format a posterior sample vector as "median (lo, hi)".
.fmt <- function(x, digits = 2L) {
  x <- x[is.finite(x)]
  if (length(x) == 0L) return(NA_character_)
  q <- quantile(x, CI_PROBS)
  sprintf("%.*f (%.*f, %.*f)", digits, q[2L], digits, q[1L], digits, q[3L])
}

# Extract posterior summaries and LOO from one arm's result slot.
.extract_summaries <- function(res) {
  if (is.null(res) || isTRUE(res$skipped) || is.null(res$fit)) return(NULL)
  sims <- tryCatch(rstan::extract(res$fit), error = function(e) NULL)
  if (is.null(sims)) return(NULL)

  n_datasets  <- length(res$datasets)
  pm          <- sims$pred_median[is.finite(sims$pred_median)]
  pq          <- sims$pred_q95[is.finite(sims$pred_q95)]
  tau_raw     <- if (n_datasets >= 5L) sims$tau else NULL
  loo_res     <- .compute_loo_elpd(res$fit, n_datasets)

  list(
    pred_median_fmt   = .fmt(pm, 1L),
    pred_q95_fmt      = .fmt(pq, 1L),
    pred_median_med   = median(pm),
    pred_q95_med      = median(pq),
    pred_median_width = diff(quantile(pm, c(0.025, 0.975))),
    tau_fmt           = if (!is.null(tau_raw)) .fmt(tau_raw, 2L) else "— (n<5)",
    tau_med           = if (!is.null(tau_raw)) median(tau_raw)   else NA_real_,
    elpd              = loo_res$elpd,
    elpd_se           = loo_res$se,
    n_k_high          = loo_res$n_k_high,
    n_datasets        = n_datasets
  )
}

# Compute distributional metrics between two posterior-median predictive CDFs.
#
# Uses the posterior-median CDF (the draw whose CDF is closest to the
# median across all draws) as a single representative distribution.  W2 is
# in the same units as the outcome (days); JS is in bits (base-2).  OVL is
# the overlap coefficient ∫ min(f_ref, f_arm) dx ∈ [0, 1].
#
# Also returns tail probabilities P(T > d) at each threshold in thr_days.
# Returns NULL when either fit is absent or CDF computation fails.
.compute_dist_metrics <- function(fit_ref, fit_arm, dist_name,
                                  thr_days = TAIL_THRESHOLDS) {
  if (is.null(fit_ref) || is.null(fit_arm)) return(NULL)

  cdf_name <- .cdf_dist_name(dist_name)

  # Determine x upper bound from the upper tail of pred_q95 across both fits.
  .q99_pred_q95 <- function(f) {
    s <- tryCatch(rstan::extract(f, pars = "pred_q95")$pred_q95, error = function(e) NULL)
    if (is.null(s) || length(s) == 0L) return(30)
    quantile(s[is.finite(s)], 0.99, na.rm = TRUE)
  }
  x_max <- max(.q99_pred_q95(fit_ref), .q99_pred_q95(fit_arm)) * 1.1
  x_max <- max(x_max, max(thr_days) * 1.2, 14)

  x_seq <- seq(0.001, x_max, length.out = 1000L)

  cdf_ref_obj <- tryCatch(
    compute_predictive_cdf(fit_ref, cdf_name, x_seq = x_seq, n_draws = N_CDF_DRAWS),
    error = function(e) NULL
  )
  cdf_arm_obj <- tryCatch(
    compute_predictive_cdf(fit_arm, cdf_name, x_seq = x_seq, n_draws = N_CDF_DRAWS),
    error = function(e) NULL
  )
  if (is.null(cdf_ref_obj) || is.null(cdf_arm_obj)) return(NULL)

  # Posterior-median CDF: clamp to [ε, 1−ε] for numerical stability.
  F_ref <- pmax(pmin(cdf_ref_obj$summary$median, 1 - 1e-9), 1e-9)
  F_arm <- pmax(pmin(cdf_arm_obj$summary$median, 1 - 1e-9), 1e-9)

  dx <- diff(x_seq)[1L]

  # PDF via forward differences; renormalise to guard against CDF
  # non-monotonicity from interpolation artefacts.
  .cdf_to_pdf <- function(F) {
    f <- c(diff(F), 0) / dx
    f <- pmax(f, 1e-12)
    f / (sum(f) * dx)
  }
  f_ref <- .cdf_to_pdf(F_ref)
  f_arm <- .cdf_to_pdf(F_arm)

  # Jensen-Shannon divergence (bits, symmetric, bounded [0, 1])
  f_mix  <- 0.5 * (f_ref + f_arm)
  JS     <- 0.5 * sum(f_ref * log2(f_ref / f_mix) * dx, na.rm = TRUE) +
            0.5 * sum(f_arm * log2(f_arm / f_mix) * dx, na.rm = TRUE)
  JS     <- pmax(JS, 0)  # guard against tiny negative values from numerics

  # Overlap coefficient
  OVL <- sum(pmin(f_ref, f_arm) * dx, na.rm = TRUE)

  # Wasserstein-2 via quantile-function L2 norm
  # Q(p) = inf{x : F(x) >= p} approximated by linear interpolation.
  p_grid <- seq(0.001, 0.999, length.out = 500L)
  .quantile_fun <- function(F_vals) {
    sapply(p_grid, function(p) {
      idx <- which(F_vals >= p)[1L]
      if (is.na(idx)) return(x_seq[length(x_seq)])
      if (idx == 1L)  return(x_seq[1L])
      # Linear interpolation between grid points
      x_seq[idx - 1L] +
        (p - F_vals[idx - 1L]) / (F_vals[idx] - F_vals[idx - 1L]) *
        (x_seq[idx] - x_seq[idx - 1L])
    })
  }
  Q_ref <- .quantile_fun(F_ref)
  Q_arm <- .quantile_fun(F_arm)
  W2    <- sqrt(mean((Q_ref - Q_arm)^2, na.rm = TRUE))

  # Tail probabilities P(T > d) = 1 - F(d) at each threshold.
  .tail_prob <- function(F_vals, d) {
    idx <- which(x_seq >= d)[1L]
    if (is.na(idx)) return(0)
    1 - F_vals[idx]
  }
  tail_ref <- setNames(sapply(thr_days, .tail_prob, F_vals = F_ref), paste0("d", thr_days))
  tail_arm <- setNames(sapply(thr_days, .tail_prob, F_vals = F_arm), paste0("d", thr_days))

  list(
    W2       = round(W2,  3L),
    JS       = round(JS,  4L),
    OVL      = round(OVL, 4L),
    tail_ref = tail_ref,
    tail_arm = tail_arm
  )
}


