# ── 7. Fitting helper ─────────────────────────────────────────────────────────

.fit_one <- function(datasets, dist_name, arm, pathogen) {
  dist_type <- DIST_CODES[[dist_name]]

  stan_data <- tryCatch(
    prepare_stan_data_from_datasets(datasets, dist_type = dist_type),
    error = function(e) {
      message("  [SKIP] prepare_stan_data failed for ",
              pathogen, "/", arm, "/", dist_name, ": ", conditionMessage(e))
      NULL
    }
  )
  if (is.null(stan_data)) return(NULL)
  stan_data <- update_phi_prior(stan_data, datasets)

  fit <- tryCatch(
    rstan::sampling(
      stan_model,
      data    = stan_data,
      chains  = CHAINS,
      iter    = ITER,
      warmup  = WARMUP,
      thin    = THIN,
      control = CONTROL,
      seed    = SEED,
      refresh = 200
    ),
    error = function(e) {
      message("  [FAIL] sampling failed for ",
              pathogen, "/", arm, "/", dist_name, ": ", conditionMessage(e))
      NULL
    }
  )

  list(fit = fit, stan_data = stan_data, datasets = datasets)
}


