    s_A <- .extract_summaries(res_A)
    s_B <- .extract_summaries(res_B)
    s_C <- .extract_summaries(res_C)

    if (is.null(s_C)) next  # arm C is the reference; skip row if absent

    # ── Distributional metrics (if CDF computation is enabled) ────────────────
    dm_CA <- dm_CB <- dm_AB <- NULL
    if (COMPUTE_CDF_METRICS &&
        !is.null(res_C) && !isTRUE(res_C$skipped) && !is.null(res_C$fit)) {

      message("  Computing CDF metrics: ", pathogen, " / ", dist_name)

      if (!is.null(res_A) && !isTRUE(res_A$skipped) && !is.null(res_A$fit))
        dm_CA <- .compute_dist_metrics(res_C$fit, res_A$fit, dist_name)

      if (!is.null(res_B) && !isTRUE(res_B$skipped) && !is.null(res_B$fit))
        dm_CB <- .compute_dist_metrics(res_C$fit, res_B$fit, dist_name)

      if (!is.null(res_A) && !isTRUE(res_A$skipped) && !is.null(res_A$fit) &&
          !is.null(res_B) && !isTRUE(res_B$skipped) && !is.null(res_B$fit))
        dm_AB <- .compute_dist_metrics(res_A$fit, res_B$fit, dist_name)
    }

    # ── Helpers ───────────────────────────────────────────────────────────────
    .n <- function(res) {
      if (is.null(res) || isTRUE(res$skipped)) NA_integer_
      else length(res$datasets)
    }
    .delta <- function(s_ref, s_arm, field) {
      if (is.null(s_ref) || is.null(s_arm)) NA_real_
      else round(s_ref[[field]] - s_arm[[field]], 2L)
    }
    .ratio <- function(s_arm, s_ref) {
      # arm_width / ref_width; > 1 means arm is wider (federated is tighter)
      if (is.null(s_arm) || is.null(s_ref)) NA_real_
      else round(s_arm$pred_median_width / s_ref$pred_median_width, 3L)
    }
    .norm_shift <- function(s_arm, s_ref) {
      # (ref_median − arm_median) / arm_width
      if (is.null(s_arm) || is.null(s_ref)) NA_real_
      else round((s_ref$pred_median_med - s_arm$pred_median_med) /
                   s_arm$pred_median_width, 3L)
    }
    .dm_field <- function(dm, field) {
      if (is.null(dm)) NA_real_ else dm[[field]]
    }
    .tail <- function(dm, side, threshold) {
      # side = "tail_ref" (arm C) or "tail_arm" (the other arm)
      key <- paste0("d", threshold)
      if (is.null(dm) || is.null(dm[[side]])) NA_real_
      else round(dm[[side]][[key]], 4L)
    }

    # ── Tail probability columns ───────────────────────────────────────────────
    tail_cols <- list()
    for (d in TAIL_THRESHOLDS) {
      tail_cols[[paste0("ptail_A_", d)]] <- .tail(dm_CA, "tail_arm", d)
      tail_cols[[paste0("ptail_B_", d)]] <- .tail(dm_CB, "tail_arm", d)
      tail_cols[[paste0("ptail_C_", d)]] <- .tail(dm_CA, "tail_ref", d)
    }

    row <- c(
      list(
        pathogen  = pathogen,
        dist      = dist_labels[[dist_name]],
        n_indiv   = .n(res_A),
        n_sumstat = .n(res_B),
        n_total   = .n(res_C),

        # ── Arm A: individual-level only ─────────────────────────────────────
        A_pred_median = if (!is.null(s_A)) s_A$pred_median_fmt else NA_character_,
        A_pred_q95    = if (!is.null(s_A)) s_A$pred_q95_fmt    else NA_character_,
        A_tau         = if (!is.null(s_A)) s_A$tau_fmt         else NA_character_,
        A_width       = if (!is.null(s_A)) round(s_A$pred_median_width, 3L) else NA_real_,
        A_elpd        = if (!is.null(s_A) && !is.na(s_A$elpd)) round(s_A$elpd, 1L) else NA_real_,
        A_elpd_se     = if (!is.null(s_A) && !is.na(s_A$elpd_se)) round(s_A$elpd_se, 1L) else NA_real_,
        A_n_k_high    = if (!is.null(s_A)) s_A$n_k_high else NA_integer_,

        # ── Arm B: summary-statistics only ──────────────────────────────────
        B_pred_median = if (!is.null(s_B)) s_B$pred_median_fmt else NA_character_,
        B_pred_q95    = if (!is.null(s_B)) s_B$pred_q95_fmt    else NA_character_,
        B_tau         = if (!is.null(s_B)) s_B$tau_fmt         else NA_character_,
        B_width       = if (!is.null(s_B)) round(s_B$pred_median_width, 3L) else NA_real_,
        B_elpd        = if (!is.null(s_B) && !is.na(s_B$elpd)) round(s_B$elpd, 1L) else NA_real_,
        B_elpd_se     = if (!is.null(s_B) && !is.na(s_B$elpd_se)) round(s_B$elpd_se, 1L) else NA_real_,
        B_n_k_high    = if (!is.null(s_B)) s_B$n_k_high else NA_integer_,

        # ── Arm C: federated ─────────────────────────────────────────────────
        C_pred_median = s_C$pred_median_fmt,
        C_pred_q95    = s_C$pred_q95_fmt,
        C_tau         = s_C$tau_fmt,
        C_width       = round(s_C$pred_median_width, 3L),
        C_elpd        = if (!is.na(s_C$elpd)) round(s_C$elpd, 1L) else NA_real_,
        C_elpd_se     = if (!is.na(s_C$elpd_se)) round(s_C$elpd_se, 1L) else NA_real_,
        C_n_k_high    = s_C$n_k_high,

        # ── Differences: federated minus each arm ───────────────────────────
        delta_CA_median = .delta(s_C, s_A, "pred_median_med"),
        delta_CA_q95    = .delta(s_C, s_A, "pred_q95_med"),
        delta_CB_median = .delta(s_C, s_B, "pred_median_med"),
        delta_CB_q95    = .delta(s_C, s_B, "pred_q95_med"),

        # ── Interval ratio: arm_width / C_width  (> 1 = federated is tighter) ──
        ratio_CA = .ratio(s_A, s_C),
        ratio_CB = .ratio(s_B, s_C),

        # ── Normalised shift: (C_median − arm_median) / arm_width ──────────
        norm_shift_CA = .norm_shift(s_A, s_C),
        norm_shift_CB = .norm_shift(s_B, s_C),

        # ── Distributional metrics (A vs C) ──────────────────────────────────
        W2_CA  = .dm_field(dm_CA, "W2"),
        JS_CA  = .dm_field(dm_CA, "JS"),
        OVL_CA = .dm_field(dm_CA, "OVL"),

        # ── Distributional metrics (B vs C) ──────────────────────────────────
        W2_CB  = .dm_field(dm_CB, "W2"),
        JS_CB  = .dm_field(dm_CB, "JS"),
        OVL_CB = .dm_field(dm_CB, "OVL"),

        # ── Distributional metrics (A vs B) ──────────────────────────────────
        W2_AB  = .dm_field(dm_AB, "W2"),
        JS_AB  = .dm_field(dm_AB, "JS"),
        OVL_AB = .dm_field(dm_AB, "OVL")
      ),
      tail_cols
    )

    rows[[length(rows) + 1L]] <- as.data.frame(row, stringsAsFactors = FALSE)
  }
}

comparison_tbl <- if (length(rows) > 0L) {
  tbl <- do.call(rbind, rows)
  rownames(tbl) <- NULL
  tbl
} else {
  message("WARNING: no rows in comparison table — check fitting completed.")
  data.frame()
}


