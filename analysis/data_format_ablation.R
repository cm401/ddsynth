    ablation_results[[pathogen]] <- list()

  arms <- .make_arms(eligible_pathogens[[pathogen]])

  all_done <- all(vapply(ARM_LABELS, function(arm) {
    all(vapply(names(DIST_CODES), function(d) {
      !is.null(ablation_results[[pathogen]][[arm]][[d]])
    }, logical(1L)))
  }, logical(1L)))

  if (all_done) {
    message("  All fits already complete — nothing new to do.")
    next
  }

  for (arm in ARM_LABELS) {

    arm_datasets <- arms[[arm]]

    if (is.null(ablation_results[[pathogen]][[arm]]))
      ablation_results[[pathogen]][[arm]] <- list()

    n_arm <- length(arm_datasets)
    if (n_arm < MIN_DATASETS_PER_ARM) {
      message("\n  [SKIP] ", arm, ": only ", n_arm,
              " dataset(s) (min = ", MIN_DATASETS_PER_ARM, ").")
      next
    }

    message("\n  Arm: ", arm, "  (n_datasets = ", n_arm, ")")

    for (dist_name in names(DIST_CODES)) {

      if (!is.null(ablation_results[[pathogen]][[arm]][[dist_name]])) {
        message("  [SKIP] ", pathogen, " / ", arm, " / ", dist_name,
                " — already in results.")
        next
      }

      if (dist_name == "gengamma" &&
          !should_attempt_gg(arm_datasets, verbose = FALSE)) {
        message("  [SKIP] ", pathogen, " / ", arm,
                " / gengamma — identifiability heuristic.")
        ablation_results[[pathogen]][[arm]][["gengamma"]] <-
          list(skipped = TRUE, reason = "identifiability_heuristic",
               datasets = arm_datasets)
        next
      }

      if (dist_name == "gamma" &&
          !gamma_type2_reliable(arm_datasets, verbose = FALSE)) {
        message("  [SKIP] ", pathogen, " / ", arm,
                " / gamma — gamma_type2_reliable check.")
        ablation_results[[pathogen]][[arm]][["gamma"]] <-
          list(skipped = TRUE, reason = "gamma_type2_reliable",
               datasets = arm_datasets)
        next
      }

      message("  Fitting: ", pathogen, " | ", arm, " | ", dist_name)
      ablation_results[[pathogen]][[arm]][[dist_name]] <-
        .fit_one(arm_datasets, dist_name, arm, pathogen)
    }
  }

  saveRDS(list(ablation_fits = ablation_results), OUTPUT_FILE)
  message("\n  Saved to: ", OUTPUT_FILE)
}

