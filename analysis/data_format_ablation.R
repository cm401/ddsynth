# ── 4. Dataset classification helpers ────────────────────────────────────────

.get_summary_type <- function(d) {
  if (!is.null(d$freq_lower) && !is.null(d$freq_upper) && !is.null(d$freq_count)) 5L
  else if (!is.null(d$freq_value) && !is.null(d$freq_count)) 4L
  else if (!is.null(d$mean) && !is.null(d$sd)) 3L
  else if (!is.null(d$median) && !is.null(d$Q1) && !is.null(d$Q3)) 2L
  else if (!is.null(d$median) && (!is.null(d$min) || !is.null(d$max))) 1L
  else NA_integer_
}

.make_arms <- function(datasets) {
  types <- vapply(datasets, .get_summary_type, integer(1L))
  list(
    individual_only = datasets[!is.na(types) & types %in% c(4L, 5L)],
    summary_only    = datasets[!is.na(types) & types %in% c(1L, 2L, 3L)],
    federated       = datasets
  )
}

# compute_predictive_cdf() uses "gg" for generalised gamma; all others match.
.cdf_dist_name <- function(dist_name) {
  if (dist_name == "gengamma") "gg" else dist_name
}


